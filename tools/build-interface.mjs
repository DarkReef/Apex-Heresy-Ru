/** Rebuild interface translations without reading or modifying any compendium. */
import {readFileSync, writeFileSync} from 'node:fs';
const json = path => JSON.parse(readFileSync(path, 'utf8'));
const en = json('lang/en.json'), glossary = json('localization/ru/glossary.json');
const overrides = json('localization/ru/interface-overrides.json');
const ru = Object.fromEntries(Object.entries(en).map(([key, text]) => {
    const translated = overrides[key] ?? glossary[text];
    if (!translated) throw new Error('Missing interface translation: ' + key);
    return [key, translated];
}));
writeFileSync('lang/ru.json', JSON.stringify(ru, null, 2) + '\n');
const defaults = Object.fromEntries(Object.entries(en).filter(([key]) => key.startsWith('UI.')));
writeFileSync('script/localization/environment-text.mjs',
    '// Generated by tools/build-interface.mjs. Resolve UI labels lazily; preserve user-authored text.\n' +
    'const defaults = ' + JSON.stringify(defaults, null, 2) + ';\n' +
    'export function environmentText(key, data = {}) {\n' +
    '  const translated = globalThis.game?.i18n?.format?.(key, data);\n' +
    '  const text = translated && translated !== key ? translated : defaults[key] ?? key;\n' +
    '  return typeof text === "string" ? text.replace(/\\{(\\w+)\\}/g, (match, name) => data[name] ?? match) : text;\n' +
    '}\n');
const coverage = json('localization/ru/coverage.json');
coverage.interface = {translated:Object.keys(ru).length,total:Object.keys(en).length};
writeFileSync('localization/ru/coverage.json', JSON.stringify(coverage, null, 2) + '\n');
